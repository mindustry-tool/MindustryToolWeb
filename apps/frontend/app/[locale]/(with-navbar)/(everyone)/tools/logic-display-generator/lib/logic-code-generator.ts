import type { PixelData, ProcessorCount } from './types';
import { RectangleMerger, type ColorBlock } from './rectangle-merger';

/**
 * Convert RGBA (0-255 range) to Mindustry packed color (ABGR format)
 */
export function rgbaToPacked(r: number, g: number, b: number, a: number): number {
    const packedInt = (
        (Math.floor(a) << 24) |
        (Math.floor(b) << 16) |
        (Math.floor(g) << 8) |
        (Math.floor(r))
    );
    return packedInt >>> 0;
}

class MLogic {
    chips: string[] = [];
    chip: string[] = [];
    block: string[] = [];
    chipMaxLength = 1000;
    blockMaxLength = 20;
    color: { r: number; g: number; b: number; a: number } | null = null;
    screenName: string;
    usePackedColors: boolean;

    constructor(screenName: string, usePackedColors: boolean = true) {
        this.screenName = screenName;
        this.usePackedColors = usePackedColors;
    }

    addColorBlock(rect: { x: number; y: number; width: number; height: number }) {
        const { x, y, width, height } = rect;
        this.block.push(`draw rect ${x} ${y} ${width} ${height}`);
        if (this.block.length === this.blockMaxLength - 2) {
            this.encapsulationBlock();
        }
    }

    setColor(color: { r: number; g: number; b: number; a: number }) {
        if (this.block.length > 0) {
            this.encapsulationBlock();
        }
        this.color = color;
    }

    encapsulationBlock() {
        const block = this.block;
        if (!this.color) return;

        const { r, g, b, a } = this.color;
        const colorCmd = this.usePackedColors
            ? `draw col ${rgbaToPacked(r, g, b, a)}`
            : `draw color ${r} ${g} ${b} ${a}`;

        block.unshift(colorCmd);
        block.push(`drawflush ${this.screenName}`);

        if (this.chip.length + block.length > this.chipMaxLength) {
            this.encapsulationChip();
        }

        this.chip.push(...block);
        this.block = [];
    }

    encapsulationChip() {
        this.chips.push(this.chip.join('\n'));
        this.chip = [];
    }

    getChips(): string[] {
        if (this.block.length > 0) {
            this.encapsulationBlock();
        }
        if (this.chip.length > 0) {
            this.encapsulationChip();
        }

        // Add watermark and 'end' instruction
        const watermark = 'print "Generated by Mindustry Tool Logic Display Generator"';
        return this.chips.map(chip => `${watermark}\n${chip}\nend`);
    }
}

/**
 * Generate Mindustry Logic (mlog) code from pixel data
 * Returns an array of string arrays. Each inner array contains the code(s) for one screen.
 */
export function generateLogicCode(
    screens: PixelData[][],
    _displaySize: '80x80' | '176x176' | '26x26',
    _processorCount: ProcessorCount = 1,
    usePackedColors: boolean = true,
    screenName: string = 'display1'
): string[][] {
    const screenCodes: string[][] = [];
    const merger = new RectangleMerger();

    // For tile displays with mega screen, calculate actual dimensions from pixel data
    // For normal displays, use standard dimensions
    const firstScreen = screens[0];
    if (!firstScreen || firstScreen.length === 0) {
        return [[]];
    }

    // Find max x and y to determine actual dimensions
    let maxX = 0;
    let maxY = 0;
    for (const pixel of firstScreen) {
        if (pixel.x > maxX) maxX = pixel.x;
        if (pixel.y > maxY) maxY = pixel.y;
    }

    const width = maxX + 1;
    const height = maxY + 1;

    screens.forEach((screenPixels) => {
        // Smart Optimization: Filter out transparent/invisible pixels
        // If a screen has no visible pixels, we don't generate any code for it.
        // This prevents creating unnecessary processors for empty/black screens.
        const visiblePixels = screenPixels.filter(p => p.a > 10);

        if (visiblePixels.length === 0) {
            screenCodes.push([]);
            return;
        }

        const colorBlocks = merger.pixelsToColorBlocks(visiblePixels, width, height);
        const codes = generateCodeForScreen(colorBlocks, screenName, usePackedColors);
        screenCodes.push(codes);
    });

    return screenCodes;
}

/**
 * Generate code for a single screen using MLogic class
 */
function generateCodeForScreen(
    colorBlocks: ColorBlock[],
    screenName: string,
    usePackedColors: boolean
): string[] {
    const mLogic = new MLogic(screenName, usePackedColors);
    const merger = new RectangleMerger();
    const colorMap = merger.groupByColor(colorBlocks);

    for (const [colorKey, blocks] of colorMap) {
        const parts = colorKey.split(',').map(Number);
        const color = {
            r: parts[0] ?? 0,
            g: parts[1] ?? 0,
            b: parts[2] ?? 0,
            a: parts[3] ?? 255
        };

        mLogic.setColor(color);
        blocks.forEach(block => {
            mLogic.addColorBlock(block.rect);
        });
    }

    const chips = mLogic.getChips();

    // Don't add draw clear for tile displays - causes flickering when processors loop
    // The display will start black and processors will draw on top

    return chips;
}

